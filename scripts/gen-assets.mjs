// Regenerates src/assets/images.ts (base64-embedded PNGs served by the Worker).
// OG image source: assets/og/og.html (render 1200x630 with headless Chrome -> assets/og.png).
import { readFileSync, writeFileSync } from "node:fs";
const b64 = (p) => readFileSync(new URL(`../assets/${p}`, import.meta.url)).toString("base64");
const out = `// Generated by scripts/gen-assets.mjs. Do not edit.
export const OG_PNG_B64 = "${b64("og.png")}";
export const APPLE_TOUCH_PNG_B64 = "${b64("apple-touch-icon.png")}";
export const FAVICON_PNG_B64 = "${b64("favicon-32.png")}";
`;
writeFileSync(new URL("../src/assets/images.ts", import.meta.url), out);
console.log("wrote src/assets/images.ts", out.length, "bytes");
